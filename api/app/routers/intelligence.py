@router.get("/anomalies",
            summary="Detected anomalies with baseline, deviation and drivers")
def anomalies() -> dict:
    """Served from the generated report so a page load costs no recomputation.

    Regenerated by scripts/run_anomaly_detection.py, which also verifies the detector
    against ground truth: F1/F2/F3 found, and the D1 decoy correctly silent.
    """
    md = ROOT / "reports" / "anomalies.md"
    if not md.exists():
        raise HTTPException(status_code=503, detail="Anomaly report not generated yet.")

    rows = []
    for line in md.read_text(encoding="utf-8").splitlines():
        if line.startswith("| `") and line.count("|") >= 9:
            cells = [x.strip().strip("`") for x in line.strip("|").split("|")]
            if len(cells) >= 9 and cells[0] != "Metric":
                rows.append({
                    "metric": cells[0],
                    "segment": cells[1],
                    "date": cells[2],
                    "actual": cells[3],
                    "baseline": cells[4],
                    "deviation_pct": cells[5],
                    "robust_z": cells[6],
                    "confidence": cells[7],
                    "likely_drivers": cells[8] if cells[8] not in ("-", "—") else None,
                })

    return {
        "method": ("day-of-week aware trailing baseline, robust MAD scale, dual "
                   "thresholds (statistical AND material), published false-alert budget"),
        "why_not_isolation_forest": ("on a weekly-seasonal univariate series it flags "
                                     "every weekend, misses the weekday running below "
                                     "its own weekday norm, and yields no baseline or "
                                     "explanation, so its output cannot be acted on"),
        "count": len(rows),
        "anomalies": rows[:50],
    }


def _field(body: str, label: str) -> str | None:
    """Pull a bolded table field such as **Status** | Open."""
    m = re.search(rf"\*\*{label}\*\*\s*\|?\s*([^\n|]+)", body)
    return m.group(1).strip(" |") if m else None


def _paragraph(body: str, label: str) -> str | None:
    """Pull a bolded lead-in paragraph such as **Finding.** ..."""
    m = re.search(rf"\*\*{label}\.?\*\*\s*(.+?)(?=\n\n|\n\*\*|\Z)", body, re.S)
    if not m:
        return None
    return re.sub(r"\s+", " ", re.sub(r"[*`]", "", m.group(1))).strip()


@router.get("/decisions",
            summary="Decision log - finding, evidence, confidence, action")
def decisions() -> dict:
    """Parsed from the generated DECISION_LOG.md, which is built from live queries."""
    md = ROOT / "DECISION_LOG.md"
    if not md.exists():
        raise HTTPException(status_code=503, detail="Decision log not generated yet.")

    parts = re.split(r"\n## (D-\d+) · ", md.read_text(encoding="utf-8"))
    entries = []
    for i in range(1, len(parts) - 1, 2):
        did, body = parts[i], parts[i + 1]
        entries.append({
            "id": did,
            "title": body.splitlines()[0].strip(),
            "status": _field(body, "Status"),
            "owner": _field(body, "Owner"),
            "confidence": _field(body, "Confidence"),
            "finding": _paragraph(body, "Finding"),
            "recommendation": _paragraph(body, "Recommendation"),
        })

    return {
        "note": ("the target role states that success is measured by decisions made, "
                 "not reports produced. One entry is a decision NOT to act; one was "
                 "reversed when follow-up data contradicted the first read."),
        "count": len(entries),
        "decisions": entries,
    }


@router.get("/daily-brief/latest", summary="Most recent automated operations brief")
def brief_latest() -> dict:
    md = ROOT / "reports" / "LATEST_BRIEF.md"
    stamp = ROOT / "reports" / "_freshness.json"
    if not md.exists():
        raise HTTPException(status_code=503, detail="No brief generated yet.")
    meta = json.loads(stamp.read_text(encoding="utf-8")) if stamp.exists() else {}
    return {
        "generated_at_utc": meta.get("generated_at_utc"),
        "as_of": meta.get("as_of"),
        "quality_score": meta.get("quality_score"),
        "alerts": meta.get("alerts_today"),
        "note": ("every number in the brief is computed in SQL or pandas and passed to "
                 "the template as a fact - no language model calculates anything in it"),
        "markdown": md.read_text(encoding="utf-8"),
    }


@router.get("/daily-brief/history", summary="Available brief dates")
def brief_history() -> dict:
    d = ROOT / "reports" / "briefings"
    files = sorted((p.stem for p in d.glob("*.md")), reverse=True) if d.exists() else []
    return {"count": len(files), "dates": files[:60]}
